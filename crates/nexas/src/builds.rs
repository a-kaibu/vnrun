//! Builtin numbering of the engine builds. Each exe build renumbers its builtins (an id is the
//! case of the dispatcher's switch), so the engine works in the numbering of 恋愛フェイズ (2015)
//! and translates the others. A table row is (id in the build, id in 2015, argument count); 0xffff
//! is a builtin 2015 does not have.
//!
//! The tables come from the decompiled dispatchers: the cases of two builds are aligned by the
//! similarity of their handlers, in order, since a later build inserts ids but keeps the order.
//! The build of a game is the table whose argument counts agree with most calls in System.bin.

use crate::script::{Block, Script};

pub struct Build {
    pub name: &'static str,
    rows: &'static [(u16, u16, u8)],
    /// Before 2015 (2011, 2012) the VM has no 0x2F (unsigned shift) and no 0x39/0x3A, so the ops from 0x2F
    /// on are one lower and those from 0x3D on two lower.
    old_ops: bool,
    /// 2007: the VM lacks two of the bitwise ops, so its ops from 0x13 on are two lower than 2010's.
    pub early: bool,
    /// 2006: the VM has no modulo, so its ops from 0xD on are one lower than 2007's.
    pub y2006: bool,
    /// ひなたテラス (2011): a move (0x144) goes to an offset from where the object was made
    pub relative_moves: bool,
}

