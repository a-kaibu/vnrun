impl Build {
    fn row(&self, id: u32) -> Option<&(u16, u16, u8)> {
        let i = self
            .rows
            .binary_search_by_key(&id, |r| u32::from(r.0))
            .ok()?;
        self.rows.get(i)
    }

    /// The 2015 id of builtin `id` of this build (0xffff: none).
    pub fn canonical(&self, id: u32) -> u32 {
        self.row(id).map_or(0xffff, |r| u32::from(r.1))
    }

    /// Renumbers the ops of `script` to the 2015 VM's.
    pub fn translate(&self, script: &mut Script) {
        if !self.old_ops {
            return;
        }
        let (early, y2006) = (self.early, self.y2006);
        let fix = |b: &mut Block| {
            for ins in b.init.iter_mut().chain(&mut b.code) {
                if y2006 && ins.op >= 0xd {
                    ins.op += 1;
                }
                if early && ins.op >= 0x13 {
                    ins.op += 2;
                }
                ins.op = match ins.op {
                    0x2f..=0x38 => ins.op + 1,
                    0x3d.. => ins.op + 2,
                    op => op,
                };
            }
        };
        fix(&mut script.main);
        script.funcs.values_mut().for_each(fix);
    }

    /// The build whose argument counts fit the calls of `script` best.
    pub fn detect(script: &Script) -> &'static Build {
        if script
            .main
            .code
            .iter()
            .any(|i| i.op == 7 && i.arg == (10 << 16 | 0x39))
        {
            return if script.legacy {
                &B2010_BUILD
            } else {
                &B2011H_BUILD
            };
        }
        if script.legacy
            && script
                .main
                .code
                .iter()
                .any(|i| i.op == 7 && i.arg == (10 << 16 | 0x16a))
        {
            return &B2009_BUILD;
        }
        if script.legacy
            && script
                .main
                .code
                .iter()
                .any(|i| i.op == 7 && i.arg == (10 << 16 | 0x165))
        {
            return &B2008_BUILD;
        }
        if script.legacy
            && script
                .main
                .code
                .iter()
                .any(|i| i.op == 7 && i.arg == (9 << 16 | 0xe8))
        {
            return &B2007_BUILD;
        }
        // 2006: calls a bank (0xaa, 9 arguments) and goes to a file (0xa6, 2)
        let calls = |arg: u32| {
            std::iter::once(&script.main)
                .chain(script.funcs.values())
                .flat_map(|b| b.init.iter().chain(&b.code))
                .any(|i| i.op == 7 && i.arg == arg)
        };
        if script.legacy && calls(9 << 16 | 0xaa) && calls(2 << 16 | 0xa6) {
            return &B2006_BUILD;
        }
        let mut calls = Vec::new();
        let mut collect = |b: &Block| {
            for ins in b.init.iter().chain(&b.code) {
                if ins.op == 7 && ins.arg & 0x8000 == 0 {
                    calls.push((ins.arg & 0xffff, ins.arg >> 16));
                }
            }
        };
        collect(&script.main);
        script.funcs.values().for_each(&mut collect);
        BUILDS
            .iter()
            .max_by_key(|b| {
                calls
                    .iter()
                    .filter(|&&(id, argc)| b.row(id).is_some_and(|r| u32::from(r.2) == argc))
                    .count()
            })
            .unwrap_or(&BUILDS[0])
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::script::Ins;

    #[test]
    fn identifies_the_2010_build_by_its_scene_call() {
        let mut script = Script::default();
        script.legacy = true;
        script.main.code.push(Ins {
            op: 7,
            arg: (10 << 16) | 0x39,
        });
        let build = Build::detect(&script);
        assert_eq!(build.canonical(0x39), 0x45);
        assert_eq!(build.canonical(0x3c), 0x48);
        assert_eq!(build.canonical(0x115), 0x137);
        assert_eq!(build.canonical(0x116), 0x138);
        assert_eq!(build.canonical(0x121), 0x144);
        assert_eq!(build.canonical(0x122), 0xffff);
        script.main.code.clear();
        assert_ne!(Build::detect(&script).name, B2010_BUILD.name);
    }

    #[test]
    fn identifies_the_2006_build_and_shifts_its_ops() {
        let mut script = Script::default();
        script.legacy = true;
        for arg in [9 << 16 | 0xaa, 2 << 16 | 0xa6] {
            script.main.code.push(Ins { op: 7, arg });
        }
        // store (0xd) and the label end (0x19)
        script.main.code.push(Ins { op: 0xd, arg: 0 });
        script.main.code.push(Ins { op: 0x19, arg: 0 });
        let build = Build::detect(&script);
        assert_eq!(build.name, B2006_BUILD.name);
        assert_eq!(build.canonical(0x96), 0x67);
        build.translate(&mut script);
        let ops: Vec<u32> = script.main.code.iter().map(|i| i.op).collect();
        assert_eq!(ops, [7, 7, 0xe, 0x1c]);
    }

    #[test]
    fn identifies_the_2009_build_by_its_scene_call() {
        let mut script = Script::default();
        script.legacy = true;
        script.main.code.push(Ins {
            op: 7,
            arg: (10 << 16) | 0x16a,
        });
        let build = Build::detect(&script);
        assert_eq!(build.name, B2009_BUILD.name);
        assert_eq!(build.canonical(0x44), 0x137);
        assert_eq!(build.canonical(0x159), 0x67);
    }
}

