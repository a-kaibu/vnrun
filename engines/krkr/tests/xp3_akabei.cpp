#include "../xp3_akabei.h"

#include <array>
#include <cassert>

int main()
{
    // Independent fixed vector: plaintext bytes 0..63, hash 0x12345678, seed 0x1f2e3d4c.
    const std::array<std::uint8_t, 64> ciphertext = {{
        0x34, 0x6a, 0x18, 0x0e, 0x9e, 0x30, 0x8b, 0x01, 0xc5, 0x93, 0x4c, 0x88, 0x6a, 0x40, 0xad, 0x4e,
        0xa3, 0xb7, 0xc3, 0xb3, 0x4d, 0xc6, 0x7e, 0xc7, 0xb4, 0x70, 0x2e, 0x73, 0xca, 0x29, 0x04, 0x2b,
        0x14, 0x4a, 0x38, 0x2e, 0xbe, 0x10, 0xab, 0x21, 0xe5, 0xb3, 0x6c, 0xa8, 0x4a, 0x60, 0x8d, 0x6e,
        0x83, 0x97, 0xe3, 0x93, 0x6d, 0xe6, 0x5e, 0xe7, 0x94, 0x50, 0x0e, 0x53, 0xea, 0x09, 0x24, 0x0b,
    }};
    auto bytes = ciphertext;
    vnrun::AkabeiDecrypt(0x1f2e3d4c, 0x12345678, 0, bytes.data(), bytes.size());
    for (std::size_t i = 0; i < bytes.size(); ++i) assert(bytes[i] == i);

    // Reading in arbitrary pieces must match a whole-file read, including offsets > 32 bits.
    for (std::size_t split = 1; split < bytes.size(); ++split) {
        bytes = ciphertext;
        vnrun::AkabeiDecrypt(0x1f2e3d4c, 0x12345678, 0, bytes.data(), split);
        vnrun::AkabeiDecrypt(0x1f2e3d4c, 0x12345678, (1ULL << 40) + split,
                             bytes.data() + split, bytes.size() - split);
        for (std::size_t i = 0; i < bytes.size(); ++i) assert(bytes[i] == i);
    }
    // The state ignores the seed's top bit.
    bytes = ciphertext;
    vnrun::AkabeiDecrypt(0x9f2e3d4c, 0x12345678, 0, bytes.data(), bytes.size());
    for (std::size_t i = 0; i < bytes.size(); ++i) assert(bytes[i] == i);
    // Mado uses the same state but repeats after 31 bytes.
    const std::array<std::uint8_t,64> mado={{0x78, 0x57, 0x36, 0x11, 0x38, 0x2e, 0x1c, 0x0e, 0x96, 0x1c, 0x87, 0x0f, 0xc3, 0x87, 0x48, 0x8d, 0x77, 0x54, 0x31, 0xd2, 0xa7, 0xb7, 0x87, 0xf7, 0x41, 0xc8, 0x52, 0xeb, 0xb0, 0x75, 0x3a, 0x67, 0x76, 0x15, 0x30, 0x1f, 0x0f, 0x3f, 0x2f, 0xb9, 0x3d, 0xa4, 0x2e, 0xe4, 0xa6, 0x6b, 0xac, 0x48, 0x75, 0x12, 0xf3, 0x80, 0x96, 0xa4, 0xd6, 0x6e, 0xe9, 0x71, 0xca, 0x97, 0x54, 0x19, 0x46, 0x69}};
    for(unsigned split=1;split<64;++split) {
        auto plain=mado;
        vnrun::AkabeiDecrypt(0,0x12345678,0,plain.data(),split,31);
        vnrun::AkabeiDecrypt(0,0x12345678,split,plain.data()+split,64-split,31);
        for(unsigned i=0;i<64;++i) assert(plain[i]==i);
    }
    vnrun::AkabeiDecrypt(0, 0, 0, nullptr, 0);
}
